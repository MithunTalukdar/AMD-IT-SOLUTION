export function getServiceBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  return (
    ALL_SERVICES_CATALOG.find((s) => s.slug === cleanSlug || s.id === cleanSlug) ||
    // Legacy mapping support
    ALL_SERVICES_CATALOG.find((s) => s.slug.includes(cleanSlug) || cleanSlug.includes(s.slug)) ||
    null
  );
}

export function getCategoryById(catId) {
  if (!catId) return null;
  const cleanId = catId.toLowerCase().trim();
  return CATEGORIES.find((c) => c.id === cleanId || c.slug === cleanId) || null;
}

export function getServicesByCategory(catId) {
  if (!catId || catId === 'all') return ALL_SERVICES_CATALOG;
  const cleanId = catId.toLowerCase().trim();
  return ALL_SERVICES_CATALOG.filter((s) => s.category === cleanId);
}
